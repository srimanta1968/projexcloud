/**
 * Generates the API-key scope reference in the developer hub from the checked-in
 * api_definitions tree, so it cannot drift from the routes that actually exist.
 *
 *   node scripts/verify/gen-scope-table.mjs         # fails if the doc is stale
 *   node scripts/verify/gen-scope-table.mjs --write # regenerate + sync portals
 *
 * WHY GENERATE IT
 * ---------------
 * The scope a request needs is DERIVED from its route (`<domain>.<resource>.<action>`),
 * so a hand-written table is a second copy of a rule that already exists in code.
 * It starts correct and quietly stops being correct the first time somebody adds
 * a route — and a scope table that lists an endpoint you cannot call, or omits
 * one you can, costs an integrator an afternoon.
 *
 * The source of truth is `tests/api_definitions/`, because those files are the
 * routes the platform commits to and are already kept honest by the API-test
 * runner. Deriving from the gateway at runtime would be closer to the metal but
 * would make documentation generation depend on a booted server.
 */

import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join } from 'node:path';

const DEFS = 'tests/api_definitions';
const DOC = 'docs/v3.1/developer-hub/api-keys-and-project-setup.html';
const COPIES = ['apps/tenant-admin/public/docs/hub', 'apps/tenant-workspace/public/docs/hub'];
const START = '<!-- SCOPE-TABLE:START (generated by scripts/verify/gen-scope-table.mjs) -->';
const END = '<!-- SCOPE-TABLE:END -->';
const write = process.argv.includes('--write');

/** Mirrors singularise() in packages/sdk-api-keys/src/middleware/scope.ts. */
function singularise(segment) {
  if (segment.endsWith('ies')) return `${segment.slice(0, -3)}y`;
  if (segment.endsWith('ses') || segment.endsWith('xes')) return segment.slice(0, -2);
  if (segment.endsWith('s') && !segment.endsWith('ss')) return segment.slice(0, -1);
  return segment;
}

/**
 * Surfaces an API key can never reach, whatever scopes it holds: the auth gate
 * hands these to their own credential (ADMIN_OPS_TOKEN, a SCIM bearer, a robot
 * key) before a tenant credential is even considered.
 *
 * They are excluded rather than listed, because printing a scope next to
 * `/api/admin/...` states the opposite of the truth — it reads as "hold this
 * scope and you may call it", and an integrator would waste real time acting on
 * that before discovering the route refuses them by construction.
 */
const OPERATOR_PREFIXES = ['/api/admin/', '/admin/', '/scim/'];
const COMMAND_ACK = /^\/api\/commands\/[^/]+\/ack$/;

function isOperatorSurface(endpoint) {
  const path = endpoint.split('?')[0];
  if (OPERATOR_PREFIXES.some((p) => path.startsWith(p))) return true;
  // Normalise both :param and {param} styles before testing the ack leaf.
  return COMMAND_ACK.test(path.replace(/\{[^}]+\}/g, ':p'));
}

/** Mirrors scopeForRequest(). Kept in step by tests/scope.test.ts on the code side. */
function scopeFor(method, endpoint) {
  if (isOperatorSurface(endpoint)) return null;
  const segments = endpoint
    .split('/')
    .filter((s) => s && !s.startsWith(':') && !s.startsWith('{') && !s.startsWith('*'));
  if (segments[0] !== 'api') return null;
  const rest = segments.slice(1);
  if (rest.length === 0) return null;
  const action = method === 'GET' || method === 'HEAD' ? 'read' : 'write';
  const domain = singularise(rest[0]);
  return `${domain}.${rest[1] ? singularise(rest[1]) : domain}.${action}`;
}

function walk(dir) {
  const out = [];
  for (const entry of readdirSync(dir)) {
    const p = join(dir, entry);
    if (statSync(p).isDirectory()) out.push(...walk(p));
    else if (entry.endsWith('.json')) out.push(p);
  }
  return out;
}

const escape = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

/** domain -> Set of "METHOD path -> scope" rows. */
const byDomain = new Map();
let skipped = 0;

for (const file of walk(DEFS)) {
  let def;
  try {
    def = JSON.parse(readFileSync(file, 'utf8'));
  } catch {
    skipped += 1;
    continue;
  }
  const { method, endpoint } = def;
  if (!method || !endpoint) {
    skipped += 1;
    continue;
  }
  const scope = scopeFor(method.toUpperCase(), endpoint);
  // A route outside /api takes no key scope — a health probe or an operator
  // surface. Listing one would imply a key could reach it.
  if (!scope) continue;
  const domain = scope.split('.')[0];
  if (!byDomain.has(domain)) byDomain.set(domain, new Map());
  byDomain.get(domain).set(`${method.toUpperCase()} ${endpoint}`, scope);
}

const domains = [...byDomain.keys()].sort();
const rows = [];
for (const domain of domains) {
  const entries = [...byDomain.get(domain).entries()].sort(([a], [b]) => a.localeCompare(b));
  for (const [request, scope] of entries) {
    rows.push(
      `      <tr><td><code>${escape(request)}</code></td><td><code>${escape(scope)}</code></td></tr>`,
    );
  }
}

const table = [
  START,
  `    <p class="muted">Generated from <code>${DEFS}</code> by <code>scripts/verify/gen-scope-table.mjs</code> —`,
  `    ${rows.length} endpoints across ${domains.length} domains. Do not edit by hand.`,
  '    A domain wildcard such as <code>sla.*</code> covers every row in that domain, including ones added later.</p>',
  '    <table>',
  '      <tr><th>Request</th><th>Scope required</th></tr>',
  ...rows,
  '    </table>',
  END,
].join('\n');

const doc = readFileSync(DOC, 'utf8');
const from = doc.indexOf(START);
const to = doc.indexOf(END);

let next;
if (from !== -1 && to !== -1) {
  next = doc.slice(0, from) + table + doc.slice(to + END.length);
} else {
  // First run: the generated table belongs at the END of the Scopes section, so
  // it sits under the derivation rules it is an instance of. That means
  // inserting immediately before the NEXT section heading.
  const anchor = doc.indexOf('<h2 id="project"');
  if (anchor === -1) {
    console.error('  Could not find the heading after the Scopes section to insert before.');
    process.exit(1);
  }
  next = `${doc.slice(0, anchor)}${table}\n\n${doc.slice(anchor)}`;
}

if (next === doc) {
  console.log(`  scope table is current (${rows.length} endpoints, ${domains.length} domains)`);
  process.exit(0);
}

if (!write) {
  console.log('  DRIFT: the scope table in the developer hub is stale.');
  console.log('  Re-run with --write to regenerate.');
  process.exit(1);
}

writeFileSync(DOC, next);
for (const dir of COPIES) writeFileSync(join(dir, 'api-keys-and-project-setup.html'), next);
console.log(`  wrote ${rows.length} endpoints across ${domains.length} domains`);
if (skipped) console.log(`  skipped ${skipped} definition file(s) with no method/endpoint`);
