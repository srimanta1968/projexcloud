import type { LegalExportJurisdiction } from '@projexlight/contracts';

/**
 * Jurisdiction-specific render fragments for the legal-export PDF.
 *
 * Each template returns the strings the bundler renders into the PDF:
 *   - title (cover page)
 *   - certification clause (signed by ProjexCloud + counter-sign)
 *   - chain-of-custody declaration (per-jurisdiction wording)
 *   - required regulatory disclosures (e.g. GDPR Art. 15 reference)
 *
 * Out of scope for this drop: actual notarization, court-specific
 * stamps, attorney-of-record fields. Those land per-customer as the
 * legal review (PRD §9 dependency) completes.
 */

export interface JurisdictionTemplate {
  jurisdiction: LegalExportJurisdiction;
  title: string;
  certification: string;
  chain_clause: string;
  disclosures: string[];
  /** Localized timestamp format hint for the bundler. */
  timezone_hint: string;
}

