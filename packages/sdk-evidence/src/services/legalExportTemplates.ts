const TEMPLATES: Record<string, JurisdictionTemplate> = {
  'us-court': US_COURT,
  'eu-gdpr': EU_GDPR,
  'india-it-act': INDIA_IT_ACT,
};

export function getJurisdictionTemplate(jurisdiction: LegalExportJurisdiction): JurisdictionTemplate {
  return TEMPLATES[jurisdiction] ?? DEFAULT_TEMPLATE;
}

export function registerJurisdictionTemplate(template: JurisdictionTemplate): void {
  TEMPLATES[template.jurisdiction] = template;
}

export function listJurisdictionTemplates(): JurisdictionTemplate[] {
  return Object.values(TEMPLATES);
}
